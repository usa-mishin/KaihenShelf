using System;
using System.Collections.Generic;
using System.Linq;

namespace KaihenShelf
{
    // Keep existing serialized values: Tag remains the positive tag condition.
    public enum CategoryConditionSource { Subcategory = 0, Tag = 1, TagNotContains = 2, Shop = 3, ShopNotContains = 4 }
    [Serializable] public sealed class CategoryCondition
    {
        public CategoryConditionSource source;
        public string value = "";
    }
    [Serializable] public sealed class CategoryRule
    {
        public AssetCategory category;
        public List<CategoryCondition> conditions = new List<CategoryCondition>();
    }
    public static class CategoryRules
    {
        public static List<CategoryRule> Defaults()
        {
            var rules = Enumerable.Range(0, Categories.Labels.Length).Select(i => new CategoryRule { category = (AssetCategory)i }).ToList();
            for (int i = 0; i < Categories.BoothNames.Length; i++)
                rules[(int)Categories.BoothCategories[i]].conditions.Add(new CategoryCondition { value = Categories.BoothNames[i] });
            AddSkinMaterialTag(rules);
            AddMaterialPatterns(rules);
            foreach (string shop in new[] { "GLAY Unknown", "DanaStudio" })
            {
                rules[(int)AssetCategory.Clothing].conditions.Add(new CategoryCondition { source = CategoryConditionSource.ShopNotContains, value = shop });
                rules[(int)AssetCategory.Hair].conditions.Add(new CategoryCondition { source = CategoryConditionSource.Shop, value = shop });
            }
            PrioritizeMaterial(rules);
            return rules;
        }
        public static void PrioritizeMaterial(List<CategoryRule> rules)
        {
            int material = rules.FindIndex(rule => rule.category == AssetCategory.Material);
            int texture = rules.FindIndex(rule => rule.category == AssetCategory.Texture);
            if (material < 0 || texture < 0 || material < texture) return;
            var rule = rules[material]; rules.RemoveAt(material); rules.Insert(texture, rule);
        }
        public static void AddMaterialPatterns(List<CategoryRule> rules)
        {
            var material = rules.FirstOrDefault(rule => rule.category == AssetCategory.Material);
            if (material == null) { material = new CategoryRule { category = AssetCategory.Material }; rules.Add(material); }
            foreach (string pattern in new[] { "*マテリアル*", "*material*", "*matcap*" })
                if (!material.conditions.Any(c => c.source == CategoryConditionSource.Tag && Matcher.Normalize(c.value) == pattern))
                    material.conditions.Add(new CategoryCondition { source = CategoryConditionSource.Tag, value = pattern });
        }
        // Only '*' is special. Other punctuation remains literal, and matching covers the whole tag.
        public static bool TagMatches(string tag, string pattern)
        {
            string text = Matcher.Normalize(tag), glob = Matcher.Normalize(pattern);
            if (text.Length == 0 || glob.Length == 0) return false;
            int t = 0, p = 0, star = -1, retry = 0;
            while (t < text.Length)
            {
                if (p < glob.Length && glob[p] != '*' && glob[p] == text[t]) { p++; t++; }
                else if (p < glob.Length && glob[p] == '*') { star = p++; retry = t; }
                else if (star >= 0) { p = star + 1; t = ++retry; }
                else return false;
            }
            while (p < glob.Length && glob[p] == '*') p++;
            return p == glob.Length;
        }
        public static void AddSkinMaterialTag(List<CategoryRule> rules)
        {
            var material = rules.FirstOrDefault(rule => rule.category == AssetCategory.Material);
            if (material == null) { material = new CategoryRule { category = AssetCategory.Material }; rules.Add(material); }
            if (!material.conditions.Any(condition => condition.source == CategoryConditionSource.Tag && Matcher.Normalize(condition.value) == Matcher.Normalize("肌マテリアル")))
                material.conditions.Add(new CategoryCondition { source = CategoryConditionSource.Tag, value = "肌マテリアル" });
        }
        // Remove only invalid conditions generated by 0.1.100; preserve user tags and other custom conditions.
        public static int RemoveInvalidLegacyConditions(IEnumerable<CategoryRule> rules)
        {
            var invalid = new HashSet<string>(Categories.Labels.Where(x => x != "アニメーション")
                .Concat(Enum.GetNames(typeof(AssetCategory))).Concat(new[] { "3D素材・マテリアル", "3Dマテリアル" })
                .Select(Matcher.Normalize), StringComparer.Ordinal);
            return rules.Sum(rule => rule.conditions.RemoveAll(condition => condition.source == CategoryConditionSource.Subcategory && invalid.Contains(Matcher.Normalize(condition.value))));
        }
        public static List<CategoryRule> Copy(IEnumerable<CategoryRule> source)
        {
            return source.Select(r => new CategoryRule { category = r.category, conditions = r.conditions.Select(c => new CategoryCondition { source = c.source, value = c.value }).ToList() }).ToList();
        }
        public static bool SameContents(IReadOnlyList<CategoryRule> left, IReadOnlyList<CategoryRule> right)
        {
            if (left.Count != right.Count) return false;
            for (int i = 0; i < left.Count; i++)
            {
                if (left[i].category != right[i].category || left[i].conditions.Count != right[i].conditions.Count) return false;
                for (int j = 0; j < left[i].conditions.Count; j++)
                {
                    var a = left[i].conditions[j]; var b = right[i].conditions[j];
                    if (a.source != b.source || !string.Equals(a.value ?? "", b.value ?? "", StringComparison.Ordinal)) return false;
                }
            }
            return true;
        }
        public static AssetCategory Classify(string originalCategory, IEnumerable<string> tags, IEnumerable<CategoryRule> rules, string shop = "")
        {
            string subcategory = originalCategory ?? "";
            int separator = subcategory.LastIndexOf('>');
            if (separator >= 0) subcategory = subcategory.Substring(separator + 1);
            subcategory = Matcher.Normalize(subcategory);
            var tagSet = new HashSet<string>((tags ?? Array.Empty<string>()).Select(Matcher.Normalize), StringComparer.Ordinal);
            foreach (var rule in rules)
            {
                bool matched = false, excluded = false;
                foreach (var condition in rule.conditions)
                {
                    string value = Matcher.Normalize(condition.value);
                    if (value.Length == 0) continue;
                    if (condition.source == CategoryConditionSource.TagNotContains)
                    {
                        if (tagSet.Any(tag => TagMatches(tag, value))) { excluded = true; break; }
                    }
                    else if (condition.source == CategoryConditionSource.ShopNotContains)
                    {
                        if (TagMatches(shop, value)) { excluded = true; break; }
                    }
                    else if (condition.source == CategoryConditionSource.Subcategory) matched |= value == subcategory;
                    else if (condition.source == CategoryConditionSource.Tag) matched |= tagSet.Any(tag => TagMatches(tag, value));
                    else if (condition.source == CategoryConditionSource.Shop) matched |= TagMatches(shop, value);
                }
                // Positive conditions are OR; every exclusion must pass. Exclusion alone cannot claim all items.
                if (matched && !excluded) return rule.category;
            }
            return AssetCategory.Other;
        }
    }
}
